-- Separate temporary preview and explicitly authorized asset output.
local A=game:GetService("AssetService")
local Studio=game:GetService("StudioService")
local O={MAX_DIMENSION=2048}
function O.create(mesh,anchor,o,name,source,preview,canContinue)
    local part
    local ok,result=pcall(function()
        assert(canContinue(),"Editor closed or play testing started")
        local center,size=mesh:GetCenter(),mesh:GetSize()
        assert(math.max(size.X,size.Y,size.Z)<=O.MAX_DIMENSION,"Mesh dimensions exceed 2048 studs")
        local content,id
        if preview then
            content=Content.fromObject(mesh)
        else
            local creatorId=game.CreatorId
            local creatorType=game.CreatorType==Enum.CreatorType.Group and Enum.AssetCreatorType.Group or Enum.AssetCreatorType.User
            if creatorId<=0 then creatorId=Studio:GetUserId(); creatorType=Enum.AssetCreatorType.User end
            assert(creatorId>0,"Cannot determine asset owner")
            local status,assetId=A:CreateAssetAsync(mesh,Enum.AssetType.Mesh,{
                CreatorId=creatorId,CreatorType=creatorType,Name="PathForge "..name,
                Description="Procedural mesh generated by PathForge"
            })
            assert(status==Enum.CreateAssetResult.Success and type(assetId)=="number","Mesh upload failed: "..tostring(assetId))
            id=assetId; warn("[PathForge] Uploaded mesh asset ID:",id)
            assert(canContinue(),"Editor closed or play test started; uploaded asset ID: "..tostring(id))
            content=Content.fromUri("rbxassetid://"..tostring(id))
        end
        local fidelity=preview and Enum.CollisionFidelity.Box or Enum.CollisionFidelity[o.fidelity or "Default"]
        assert(fidelity,"Invalid collision fidelity")
        local created,meshPart=pcall(function() return A:CreateMeshPartAsync(content,{CollisionFidelity=fidelity}) end)
        assert(created and meshPart,"Mesh creation failed (asset "..tostring(id).."): "..tostring(meshPart))
        part=meshPart
        assert(canContinue(),"Editor closed or play testing started")
        if id then part:SetAttribute("PathForgeMeshAssetId",id) end
        part.Name=name
        part.Size=Vector3.new(math.max(size.X,0.001),math.max(size.Y,0.001),math.max(size.Z,0.001))
        part.CFrame=CFrame.new(anchor+center)
        part.Anchored=true; part.CanCollide=not preview and o.collide; part.CanTouch=false
        if preview then part.CanQuery=false; part.Archivable=false end
        if source then
            part.Material=source.Material; part.MaterialVariant=source.MaterialVariant
            part.Color=source.Color; part.Transparency=source.Transparency; part.Reflectance=source.Reflectance
            part.TextureContent=source.TextureContent
            part.DoubleSided=source.DoubleSided; part.CastShadow=source.CastShadow
            for _,child in ipairs(source:GetChildren()) do
                if child:IsA("SurfaceAppearance") and child.Archivable then child:Clone().Parent=part end
            end
        end
        return part
    end)
    if not ok then if part then part:Destroy() end; error(result,0) end
    return result
end
return O
