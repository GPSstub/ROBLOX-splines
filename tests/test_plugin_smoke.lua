-- Loads the real plugin script in a fake Studio and clicks through the main flows.
local t=require('harness').new()
local saved={game=game,workspace=workspace,plugin=plugin,task=task,warn=warn}
local env=require('studio_mock').install()
local V=Vector3.new
local function ok(msg)
    local s=env.status()
    assert(s and not s:find("must") and not s:find("Select") and not s:find("budget") and not s:find("Invalid"),(msg or "status")..": "..tostring(s))
end
local function model()
    for _,c in ipairs(env.workspace:GetChildren()) do if c:GetAttribute("PathForgeSchema")==1 then return c end end
end

t.check("plugin loads and builds its UI",function()
    env.load()
    env.find("Generate / update saved path","TextButton")
    env.find("Create a path or load a saved PathForge model.","TextLabel")
end)
t.check("add points in the viewport",function()
    env.click("Add points in viewport")
    env.clickViewport(V(0,0,0)); env.clickViewport(V(0,0,-20)); env.clickViewport(V(20,0,-30))
    env.find("3 points   |   Node 3   |   New path","TextLabel")
    env.click("Stop viewport editing")
    assert(env.workspace:FindFirstChild("_PathForgeDraft"),"draft guides missing")
end)
t.check("preview builds part-based generators without saving",function()
    env.click("Preview now (no upload)")
    local s=env.status(); assert(s:find("^Preview ready"),s)
    local draft=env.workspace:FindFirstChild("_PathForgeDraft")
    local previewFolder=draft:FindFirstChild("Preview")
    assert(previewFolder and #previewFolder:FindFirstChild("G01_Rail"):GetChildren()>50)
end)
t.check("stack: add a Wall generator and generate both",function()
    env.click("Add generator")
    env.click("Wall")
    env.find("Generator 2 / 2  |  Wall","TextLabel")
    env.setField("Height / base elevation",6)
    env.click("Generate / update saved path")
    ok("generate")
    local m=assert(model(),"no model")
    local gen=m:FindFirstChild("Generated")
    assert(gen:FindFirstChild("G01_Rail") and gen:FindFirstChild("G02_Wall") and gen:FindFirstChild("RepeatLayers"))
    assert(m:FindFirstChild("PathData"):FindFirstChild("Generators"),"format 2 data missing")
    assert(env.recordings==1)
end)
t.check("mesh generator refuses to generate without authorization",function()
    env.click("Add generator"); env.click("Extrude")
    env.click("Generate / update saved path")
    local s=env.status(); assert(s:find("Authorize mesh uploads",1,true),s)
    env.click("Remove generator")
    env.find("Generator 2 / 2  |  Wall","TextLabel")
end)
t.check("load restores the generator stack",function()
    local m=model()
    env.click("New path / clear draft")
    env.find("0 points   |   Node 0   |   New path","TextLabel")
    env.selection={m:FindFirstChild("Generated")}
    env.click("Load selected saved path")
    ok("load")
    env.find("3 points   |   Node 1   |   Editing saved path","TextLabel")
    env.find("Generator 1 / 2  |  Rail","TextLabel")
    env.click("Next generator")
    env.find("Generator 2 / 2  |  Wall","TextLabel")
end)
t.check("update keeps one model and replaces its output",function()
    env.click("Generator enabled: ON")
    env.click("Generate / update saved path")
    ok("update")
    local count=0
    for _,c in ipairs(env.workspace:GetChildren()) do if c:GetAttribute("PathForgeSchema")==1 then count+=1 end end
    assert(count==1,"models "..count)
    local gen=model():FindFirstChild("Generated")
    assert(gen:FindFirstChild("G01_Rail") and not gen:FindFirstChild("G02_Wall"),"disabled generator was built")
end)
t.check("invalid field shows an error and keeps the model",function()
    env.setField("Width / rail gauge / diameter",0)
    env.click("Generate / update saved path")
    local s=env.status(); assert(s:find("width must be between",1,true),s)
    assert(model():FindFirstChild("Generated"):FindFirstChild("G01_Rail"))
end)
t.check("play testing clears draft and preview",function()
    env.running=true; env.heartbeat:Fire()
    assert(not env.workspace:FindFirstChild("_PathForgeDraft"))
    env.running=false
end)
for k,v in pairs(saved) do _G[k]=v end
return t.finish()
