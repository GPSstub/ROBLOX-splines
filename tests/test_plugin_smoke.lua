-- Loads the real plugin script in a fake Studio and clicks through the main flows.
local t=require('harness').new()
local saved={game=game,workspace=workspace,plugin=plugin,task=task,warn=warn}
local env=require('studio_mock').install()
local V=Vector3.new
local function ok(msg)
    local s=env.status()
    assert(s and not s:find("must") and not s:find("Select") and not s:find("budget") and not s:find("Invalid"),(msg or "status")..": "..tostring(s))
end
local function model()
    for _,c in ipairs(env.workspace:GetChildren()) do if c:GetAttribute("PathForgeSchema")==1 then return c end end
end

t.check("plugin loads and builds its UI",function()
    env.load()
    env.find("Generate / update saved path","TextButton")
    env.find("Create a path or load a saved PathForge model.","TextLabel")
end)
t.check("add points in the viewport",function()
    env.click("Add points in viewport")
    env.clickViewport(V(0,0,0)); env.clickViewport(V(0,0,-20)); env.clickViewport(V(20,0,-30))
    env.find("3 points   |   Node 3   |   New path","TextLabel")
    env.click("Stop viewport editing")
    assert(env.workspace:FindFirstChild("_PathForgeDraft"),"draft guides missing")
end)
t.check("preview builds part-based generators without saving",function()
    env.click("Preview now (no upload)")
    local s=env.status(); assert(s:find("^Preview ready"),s)
    local draft=env.workspace:FindFirstChild("_PathForgeDraft")
    local previewFolder=draft:FindFirstChild("Preview")
    assert(previewFolder and #previewFolder:FindFirstChild("G01_Rail"):GetChildren()>50)
end)
t.check("stack: add a Wall generator and generate both",function()
    env.click("Add generator")
    env.click("Wall")
    env.find("Generator 2 / 2  |  Wall","TextLabel")
    env.setField("Height / base elevation",6)
    env.click("Generate / update saved path")
    ok("generate")
    local m=assert(model(),"no model")
    local gen=m:FindFirstChild("Generated")
    assert(gen:FindFirstChild("G01_Rail") and gen:FindFirstChild("G02_Wall") and gen:FindFirstChild("RepeatLayers"))
    assert(m:FindFirstChild("PathData"):FindFirstChild("Generators"),"format 2 data missing")
    assert(env.recordings==1)
end)
t.check("mesh generator refuses to generate without authorization",function()
    env.click("Add generator"); env.click("Extrude")
    env.click("Generate / update saved path")
    local s=env.status(); assert(s:find("Authorize mesh uploads",1,true),s)
    env.click("Remove generator")
    env.find("Generator 2 / 2  |  Wall","TextLabel")
end)
t.check("load restores the generator stack",function()
    local m=model()
    env.click("New path / clear draft")
    env.find("0 points   |   Node 0   |   New path","TextLabel")
    env.selection={m:FindFirstChild("Generated")}
    env.click("Load selected saved path")
    ok("load")
    env.find("3 points   |   Node 1   |   Editing saved path","TextLabel")
    env.find("Generator 1 / 2  |  Rail","TextLabel")
    env.click("Next generator")
    env.find("Generator 2 / 2  |  Wall","TextLabel")
end)
t.check("update keeps one model and replaces its output",function()
    env.click("Generator enabled: ON")
    env.click("Generate / update saved path")
    ok("update")
    local count=0
    for _,c in ipairs(env.workspace:GetChildren()) do if c:GetAttribute("PathForgeSchema")==1 then count+=1 end end
    assert(count==1,"models "..count)
    local gen=model():FindFirstChild("Generated")
    assert(gen:FindFirstChild("G01_Rail") and not gen:FindFirstChild("G02_Wall"),"disabled generator was built")
end)
t.check("invalid field shows an error and keeps the model",function()
    env.setField("Width / rail gauge / diameter",0)
    env.click("Generate / update saved path")
    local s=env.status(); assert(s:find("width must be between",1,true),s)
    assert(model():FindFirstChild("Generated"):FindFirstChild("G01_Rail"))
end)
t.check("library: apply a built-in material to a slot and generate",function()
    env.setField("Width / rail gauge / diameter",3.2)
    env.click("Generator enabled: OFF")
    env.click("Previous generator")
    env.find("Generator 1 / 2  |  Rail","TextLabel")
    env.click("Next material") -- 2nd built-in: Asphalt (worn)
    env.click("Apply material to current slot")
    env.find("Asphalt / default / 0 textures","TextLabel")
    env.click("Generate / update saved path")
    ok("generate with library material")
    local foot=model():FindFirstChild("Generated"):FindFirstChild("G01_Rail"):FindFirstChild("RailFoot")
    assert(foot.Material.Name=="Asphalt",foot.Material.Name)
end)
t.check("library: save a recipe and load it into a new draft",function()
    env.setField("Name for saving","Two rails")
    env.click("Save current setup as recipe")
    ok("save recipe")
    env.find("1 / 1  |  Two rails","TextLabel")
    env.click("New path / clear draft")
    env.find("Generator 1 / 1  |  Rail","TextLabel")
    env.click("Load recipe into draft")
    ok("load recipe")
    env.find("Generator 1 / 2  |  Rail","TextLabel")
    env.find("Asphalt / default / 0 textures","TextLabel")
end)
t.check("library: add a workspace model and use it as a Custom asset",function()
    local lamp=Instance.new("Model"); lamp.Name="Lamp"; Instance.new("Part",lamp).Name="Pole"; lamp.Parent=env.workspace
    env.selection={lamp}
    env.setField("Name for saving","Street lamp")
    env.click("Add selected model to library")
    ok("add asset")
    env.find("1 / 1  |  Street lamp","TextLabel")
    env.click("Use as Custom asset")
    env.find("Asset: Street lamp","TextLabel")
    env.click("Add as repeat layer")
    env.find("1 / 1  |  Street lamp","TextLabel")
end)
local function newRoad(a,b)
    env.click("New path / clear draft")
    env.click("Road")
    if pcall(env.find,"Curve: Smooth spline","TextButton") then env.click("Curve: Smooth spline") end
    env.click("Add points in viewport")
    env.clickViewport(a); env.clickViewport(b)
    env.click("Stop viewport editing")
end
local function newest()
    local list=env.workspace:GetChildren()
    for i=#list,1,-1 do if list[i]:GetAttribute("PathForgeSchema")==1 then return list[i] end end
end
t.check("junctions: a road crossing another road gets a pad",function()
    newRoad(V(100,0,0),V(160,0,0))
    env.click("Generate / update saved path"); ok("road A")
    newRoad(V(130,0,-30),V(130,0,30))
    env.click("Generate / update saved path"); ok("road B")
    local gen=newest():FindFirstChild("Generated")
    local pads=gen:FindFirstChild("Junctions")
    assert(pads and #pads:GetChildren()==1,"no junction pad")
    assert(#gen:FindFirstChild("G01_Road"):GetChildren()>2,"road B was not cut")
end)
t.check("branches: snap a nearby end onto road A",function()
    newRoad(V(110,0,3),V(110,0,40))
    env.click("Snap path ends onto nearby paths")
    local s=env.status(); assert(s:find("Snapped 1",1,true),s)
    env.find("2 points   |   Node 2   |   New path","TextLabel")
    env.click("Generate / update saved path"); ok("branch")
    assert(newest():FindFirstChild("Generated"):FindFirstChild("Junctions"),"T junction missing")
end)
t.check("junctions can be turned off",function()
    newRoad(V(150,0,-30),V(150,0,30))
    env.click("Road junctions: ON")
    env.click("Generate / update saved path"); ok("no junctions")
    assert(not newest():FindFirstChild("Generated"):FindFirstChild("Junctions"))
end)
t.check("terrain: drape onto a hill and fill/carve along the path",function()
    newRoad(V(300,0,0),V(360,0,0))
    env.ground=function(x) return math.max(0,10-math.abs(x-330)/2) end
    env.setField("Drape resample spacing (0 = keep points)",10)
    env.click("Drape points onto ground")
    local s=env.status(); assert(s:find("Draped 7 of 7",1,true),s)
    env.click("Fill and carve terrain along path")
    s=env.status(); assert(s:find("^Terrain: "),s)
    local mats={}
    for _,f in ipairs(env.fills) do mats[f.material]=(mats[f.material] or 0)+1 end
    assert(mats.Air and mats.Ground and mats.Air==mats.Ground,"fills")
    env.ground=nil
end)
local function scatterBox()
    for _,c in ipairs(env.workspace:GetChildren()) do if c:GetAttribute("PathForgeScatter")==1 then return c end end
end
t.check("scatter: along the path, then brush paint and erase",function()
    local tree=Instance.new("Model"); tree.Name="Tree"; Instance.new("Part",tree); tree.Parent=env.workspace
    local rock=Instance.new("Part"); rock.Name="Rock"; rock.Parent=env.workspace
    env.selection={tree,rock}
    env.click("Use selected models as scatter assets")
    env.find("Scatter assets: Tree, Rock","TextLabel")
    newRoad(V(500,0,0),V(600,0,0))
    env.click("Scatter along path")
    local s=env.status(); assert(s:find("^Scattered 24 assets"),s)
    local box=assert(scatterBox(),"no scatter model")
    assert(#box:GetChildren()==24)
    local before=env.recordings
    env.click("Brush: paint")
    env.rayHit=V(700,0,50); env.mouse.Button1Down:Fire()
    env.rayHit=V(720,0,50); env.mouse.Move:Fire()
    env.mouse.Button1Up:Fire()
    s=env.status(); assert(s:find("^Painted"),s)
    local painted=#box:GetChildren()-24
    assert(painted>0 and env.recordings==before+1,"one undo step per stroke")
    env.click("Brush: erase")
    env.rayHit=V(700,0,50); env.mouse.Button1Down:Fire(); env.mouse.Button1Up:Fire()
    s=env.status(); assert(s:find("^Erased"),s)
    assert(#box:GetChildren()<24+painted,"nothing erased")
    env.click("Stop viewport editing")
end)
t.check("ux: draft undo/redo, shortcuts and red invalid fields",function()
    env.click("New path / clear draft")
    env.click("Add points in viewport")
    env.clickViewport(V(0,0,0)); env.clickViewport(V(0,0,-10)); env.clickViewport(V(0,0,-20))
    env.click("Stop viewport editing")
    env.click("Undo draft edit")
    env.find("2 points   |   Node 2   |   New path","TextLabel")
    env.actions.PathForgeUndo.Triggered:Fire()
    env.find("1 points   |   Node 1   |   New path","TextLabel")
    env.actions.PathForgeRedo.Triggered:Fire(); env.click("Redo draft edit")
    env.find("3 points   |   Node 3   |   New path","TextLabel")
    env.actions.PathForgeDelete.Triggered:Fire()
    env.find("2 points   |   Node 2   |   New path","TextLabel")
    env.actions.PathForgePreview.Triggered:Fire()
    local s=env.status(); assert(s:find("^Preview ready"),s)
    -- Invalid numbers turn the box red; fixing it restores the color.
    env.setField("Segment size (studs)","abc")
    local box
    for _,d in ipairs(env.widget:GetDescendants()) do if d.ClassName=="TextBox" and d.Text=="abc" then box=d end end
    assert(box and box.TextColor3==require('Ui').C.error,"field not red")
    env.setField("Segment size (studs)",2)
    assert(box.TextColor3~=require('Ui').C.error)
    env.actions.PathForgeGenerate.Triggered:Fire(); ok("generate via shortcut")
end)
t.check("play testing clears draft and preview",function()
    env.running=true; env.heartbeat:Fire()
    assert(not env.workspace:FindFirstChild("_PathForgeDraft"))
    env.running=false
end)
for k,v in pairs(saved) do _G[k]=v end
return t.finish()
